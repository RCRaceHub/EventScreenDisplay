"""Write the Avahi (mDNS) service file from the agent's config.

Run as root before the agent starts (see the systemd unit), so the
advertised port and id always match the config:

    python3 -m eventscreen.avahi --config /etc/eventscreen/config.toml
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
from xml.sax.saxutils import escape

from . import API_VERSION, __version__, config

SERVICE_PATH = Path("/etc/avahi/services/eventscreen.service")

TEMPLATE = """<?xml version="1.0" standalone='no'?>
<!DOCTYPE service-group SYSTEM "avahi-service.dtd">
<!-- Generated by eventscreen from {config}; edit that instead. -->
<service-group>
  <name replace-wildcards="yes">EventScreen %h</name>
  <!-- What a manager browses for to find screens. -->
  <service>
    <type>_eventscreen._tcp</type>
    <port>{port}</port>
    <txt-record>id={id}</txt-record>
    <txt-record>api=/api/v{api}</txt-record>
    <txt-record>version={version}</txt-record>
  </service>
  <!-- Also shows up in generic HTTP service browsers. -->
  <service>
    <type>_http._tcp</type>
    <port>{port}</port>
    <txt-record>path=/</txt-record>
  </service>
</service-group>
"""


def render(cfg: config.Config, config_path: Path) -> str:
    return TEMPLATE.format(config=escape(str(config_path)), port=cfg.port,
                           id=escape(cfg.screen_id), api=API_VERSION, version=__version__)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="eventscreen.avahi")
    parser.add_argument("--config", type=Path, default=config.DEFAULT_CONFIG_PATH)
    parser.add_argument("--output", type=Path, default=SERVICE_PATH)
    args = parser.parse_args(argv)

    text = render(config.load(args.config), args.config)
    if args.output.exists() and args.output.read_text() == text:
        return 0
    # Avahi watches the directory and picks up the change by itself.
    tmp = args.output.with_suffix(".tmp")
    tmp.write_text(text)
    os.replace(tmp, args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
