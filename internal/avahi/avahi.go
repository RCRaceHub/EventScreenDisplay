// Package avahi writes the Avahi (mDNS) service file from the agent's
// config. The systemd unit runs "eventscreen avahi" as root before the
// agent starts, so the advertised port and id always match the config.
package avahi

import (
	"fmt"
	"html"
	"os"

	"github.com/RCRaceHub/EventScreenDisplay/internal/config"
	"github.com/RCRaceHub/EventScreenDisplay/internal/playlist"
	"github.com/RCRaceHub/EventScreenDisplay/internal/version"
)

// ServicePath is where Avahi looks for static services.
const ServicePath = "/etc/avahi/services/eventscreen.service"

const template = `<?xml version="1.0" standalone='no'?>
<!DOCTYPE service-group SYSTEM "avahi-service.dtd">
<!-- Generated by eventscreen from %[1]s; edit that instead. -->
<service-group>
  <name replace-wildcards="yes">EventScreen %%h</name>
  <!-- What a manager browses for to find screens. -->
  <service>
    <type>_eventscreen._tcp</type>
    <port>%[2]d</port>
    <txt-record>id=%[3]s</txt-record>
    <txt-record>api=/api/v%[4]s</txt-record>
    <txt-record>version=%[5]s</txt-record>
  </service>
  <!-- Also shows up in generic HTTP service browsers. -->
  <service>
    <type>_http._tcp</type>
    <port>%[2]d</port>
    <txt-record>path=/</txt-record>
  </service>
</service-group>
`

// Render is the service file for cfg, loaded from configPath.
func Render(cfg config.Config, configPath string) string {
	return fmt.Sprintf(template, html.EscapeString(configPath), cfg.Port, html.EscapeString(cfg.ScreenID),
		version.API, version.Version)
}

// Write writes the service file to output if it changed. Avahi watches the
// directory and picks the change up by itself.
func Write(cfg config.Config, configPath, output string) error {
	text := Render(cfg, configPath)
	if old, err := os.ReadFile(output); err == nil && string(old) == text {
		return nil
	}
	return playlist.WriteAtomic(output, []byte(text), 0o644)
}
